export default async function handler(req: VercelRequest, res: VercelResponse) {
    if (req.method !== "POST") {
        return res.status(405).json({ error: "Method not allowed" });
    }

    try {
        const { message, history } = req.body;

        if (!message) {
            return res.status(400).json({ error: "Message is required" });
        }

        if (!process.env.GEMINI_API_KEY) {
            return res.json({
                text: `أهلاً بك في شركة المحمدية للتخليص الجمركي! يبدو أن التطبيق لم يتم ربطه بمفتاح Gemini حتى الآن.
يمكنك التواصل مباشرة مع أ/ إسلام محمد على واتساب: 01274833844.`
            });
        }

        const ai = new GoogleGenAI({
            apiKey: process.env.GEMINI_API_KEY
        });

        const contents: any[] = [];

        if (history && Array.isArray(history)) {
            history.forEach((h: any) => {
                contents.push({
                    role: h.role === "user" ? "user" : "model",
                    parts: [{ text: h.text || "" }]
                });
            });
        }

        contents.push({
            role: "user",
            parts: [{ text: message }]
        });

        const response = await ai.models.generateContent({
            model: "gemini-2.0-flash",
            contents,
            config: {
                systemInstruction: SYSTEM_INSTRUCTION,
                temperature: 0.75
            }
        });

        return res.status(200).json({
            text:
                response.text ||
                "عذراً، لم أستطع معالجة الرد حالياً. يرجى التواصل مباشرة مع أ/ إسلام محمد على الرقم 01274833844."
        });
    } catch (error: any) {
        console.error("Error in /api/consult:", error);

        return res.status(500).json({
            error: error.message || "Something went wrong",
            text: "عذراً، حدث خطأ أثناء تشغيل المساعد الذكي. يمكنك التواصل معنا مباشرة على واتساب أو الاتصال بالرقم 01274833844."
        });
    }
}